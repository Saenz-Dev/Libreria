package co.edu.uptc.modelo;

/**
 * Enum que representa los tipos de usuario disponibles en la tienda virtual.
 * Puede ser un usuario regular o premium, determinando los beneficios y características disponibles.
 */
public enum TipoUsuarioEnum {
    /**
     * Usuario regular, sin beneficios premium.
     */
    Regular,
    /**
     * Usuario premium, con beneficios adicionales.
     */
    Premium;
}
