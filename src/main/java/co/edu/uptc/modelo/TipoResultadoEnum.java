package co.edu.uptc.modelo;

/**
 * Enum que representa los posibles resultados de una operación en la aplicación.
 * Puede indicar éxito o error en la ejecución de un proceso.
 */
public enum TipoResultadoEnum {
    /**
     * Indica que la operación fue exitosa.
     */
    EXITO,
    /**
     * Indica que la operación resultó en un error.
     */
    ERROR;
}
