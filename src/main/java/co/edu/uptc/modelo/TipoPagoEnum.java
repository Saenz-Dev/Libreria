package co.edu.uptc.modelo;

/**
 * Enum que representa los diferentes tipos de pago disponibles en la tienda virtual.
 * Permite seleccionar entre pago en efectivo o con tarjeta.
 */
public enum TipoPagoEnum {
    /**
     * Pago realizado en efectivo.
     */
    EFECTIVO,
    /**
     * Pago realizado con tarjeta de crédito o débito.
     */
    TARJETA;
}
